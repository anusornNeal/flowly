test('client image limits include exactly 25 MiB and reject empty or unsupported files',()=>{
 for(const type of ['image/png','image/jpeg','image/webp'])assert.equal(validateTaskImage({type,size:TASK_IMAGE_MAX_BYTES}),undefined);
 assert.match(validateTaskImage({type:'image/png',size:TASK_IMAGE_MAX_BYTES+1})!,/25 MiB/);
 assert.match(validateTaskImage({type:'image/png',size:0})!,/empty/);
 for(const type of ['image/svg+xml','text/html','image/gif',''])assert.match(validateTaskImage({type,size:1})!,/PNG, JPEG or WebP/);
});

test('attachment URL allowlist rejects remote, malformed and non-attachment routes',()=>{
 const id='att_12345678-1234-1234-1234-123456789abc';
 const url=`/api/task-attachments/${id}/file?projectId=proj_12345678-1234-1234-1234-123456789abc`;
 assert.equal(taskImageUrl(url),url);
 for(const source of ['https://evil.test'+url,'data:image/png;base64,AAA','javascript:alert(1)','file:///tmp/image.png','/api/screenshots/x/file','/api/settings',url+'&x=1',url+'#fragment',url.replace('/file','/../file')])assert.equal(taskImageUrl(source),undefined,source);
 assert.equal(referencedTaskImage(url,[]),undefined,'Valid URL still needs current task membership');
});

