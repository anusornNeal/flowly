import test from 'node:test';
import assert from 'node:assert/strict';
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import { createServer } from '../apps/api/src/server.js';
import { openChromium } from '../packages/capture/src/renderer.js';

test('FLY-0027 / FLY-0039 / FLY-0041: modal tabs, hierarchy, themed selects and mobile accessibility',async()=>{
 const root=fs.mkdtempSync(path.join(os.tmpdir(),'flowly-ux-'));
 const api=await createServer({root});
 const browser=await openChromium(true);
 try{
  const base=await api.listen({host:'127.0.0.1',port:0});
  const operation=async(name:string,payload:Record<string,unknown>)=>{
   const response=await api.inject({method:'POST',url:'/api/operations/'+name,payload,headers:{host:'127.0.0.1'}});
   assert.equal(response.statusCode,200,response.body);return response.json().result;
  };
  const project=await operation('project.create',{name:'UX regression',platform:'web'});
  await operation('project.create',{name:'Other project',platform:'web'});
  const parent=await operation('task.create',{projectId:project.id,title:'Parent scope',description:'# Scope\n\n'+('Long description paragraph.\n\n'.repeat(80)),acceptanceCriteria:'- [ ] Keep gates',verificationStep:'Run tests'});
  const second=await operation('task.create',{projectId:project.id,title:'Second task'});
  const child=await operation('task.subtask',{projectId:project.id,parentId:parent.id,title:'Child-only needle'});
  await operation('task.create',{projectId:project.id,title:'Standalone defect',type:'bug'});
  fs.mkdirSync('data/qa',{recursive:true});
  const page=await browser.newPage({viewport:{width:1440,height:900}});
  const errors:string[]=[];page.on('pageerror',e=>errors.push(e.message));
  page.setDefaultTimeout(7000);
  await page.addInitScript(id=>{if(window===window.top)localStorage.setItem('flowly-project',id);},project.id);
  await page.goto(base);
  await page.getByRole('button',{name:/Task Board/}).first().click();
  await page.locator('.board-task').filter({hasText:'Parent scope'}).waitFor();
  assert.equal(await page.locator('.board-task').count(),3,'Only top-level tasks and bugs appear');
  assert.equal(await page.locator('.board-task').filter({hasText:'Standalone defect'}).locator('.issue-kind').textContent(),'Bug');
  assert.equal(await page.locator('.board-task').filter({hasText:'Parent scope'}).locator('.child-blocker').textContent(),'1 unfinished subtasks block Done');
  await page.getByRole('textbox',{name:'Search tasks'}).fill('Child-only needle');
  assert.equal(await page.locator('.board-task').count(),1);
  assert.equal(await page.locator('.child-search-match').textContent(),'Matching subtask: '+child.displayId);
  const laneCount=await page.locator('.board-lane header em').allTextContents();
  assert.equal(laneCount.reduce((sum,value)=>sum+Number(value),0),3,'Search does not inflate headline counts');
  await page.getByRole('textbox',{name:'Search tasks'}).fill('');
  await page.locator('.board-task').filter({hasText:'Parent scope'}).click();
  const modal=page.getByRole('dialog');
  assert.equal(await modal.getByRole('tab').count(),4);
  await page.screenshot({path:'data/qa/ux-desktop.png'});
  const overview=modal.getByRole('tab',{name:'Overview',exact:true});
  await overview.focus();await overview.press('ArrowRight');
  assert.equal(await modal.getByRole('tab',{name:'Work',exact:true}).getAttribute('aria-selected'),'true');
  assert.equal(await page.locator(':focus').textContent(),'Work');
  await modal.getByRole('tab',{name:'Work',exact:true}).press('End');
  assert.equal(await modal.getByRole('tab',{name:'Activity',exact:true}).getAttribute('tabindex'),'0');
  await modal.getByRole('tab',{name:'Activity',exact:true}).press('Home');
  await modal.getByRole('button',{name:'Edit',exact:true}).click();
  await modal.getByRole('textbox',{name:'Title',exact:true}).fill('Unsaved scope');
  const reject=async(dialog:import('playwright').Dialog)=>{await dialog.dismiss();};page.on('dialog',reject);
  await modal.getByRole('tab',{name:'Work',exact:true}).click();
  assert.equal(await modal.getByRole('textbox',{name:'Title',exact:true}).inputValue(),'Unsaved scope');
  await modal.getByRole('button',{name:'Previous task'}).click();
  assert.equal(await modal.getByRole('textbox',{name:'Title',exact:true}).inputValue(),'Unsaved scope');
  await page.keyboard.press('Escape');
  assert.equal(await modal.isVisible(),true);
  page.off('dialog',reject);page.once('dialog',d=>void d.accept());
  await modal.getByRole('tab',{name:'QA & Review',exact:true}).click();
  assert.equal(await modal.getByRole('button',{name:'Force Done (subtasks)'}).isVisible(),true);
  await modal.getByRole('tab',{name:'Work',exact:true}).click();
  await modal.getByText('Alternatives & decision', {exact:false}).click();
  await modal.getByRole('textbox',{name:'Requirements',exact:true}).fill('Engineering draft retained');
  await modal.getByRole('tab',{name:'Activity',exact:true}).click();
  await modal.getByRole('tab',{name:'Work',exact:true}).click();
  assert.equal(await modal.getByRole('textbox',{name:'Requirements',exact:true}).inputValue(),'Engineering draft retained');
  await page.setViewportSize({width:390,height:844});
  const overflow=await modal.evaluate(el=>({width:el.clientWidth,scroll:el.scrollWidth}));
  assert.ok(overflow.scroll<=overflow.width+1,JSON.stringify(overflow));
  await page.screenshot({path:'data/qa/ux-mobile.png'});
  // Drafts in mounted Engineering panels also guard navigation away from the card.
  page.on('dialog',reject);await modal.getByRole('button',{name:'Close task details'}).click();
  assert.equal(await modal.isVisible(),true);page.off('dialog',reject);
  page.once('dialog',dialog=>void dialog.accept());
  await modal.getByRole('button').filter({hasText:child.displayId}).click();
  await modal.getByRole('heading',{name:'Child-only needle',exact:true}).waitFor();
  assert.equal(await modal.getByRole('tab',{name:'Overview',exact:true}).getAttribute('aria-selected'),'true');
  assert.equal(await modal.locator('.issue-kind').textContent(),'Subtask');
  await modal.getByRole('button',{name:'Parent: '+parent.displayId,exact:true}).click();
  await modal.getByRole('heading',{name:'Parent scope',exact:true}).waitFor();
  await modal.getByRole('tab',{name:'QA & Review',exact:true}).click();
  await modal.getByRole('button',{name:'Move to Done',exact:true}).click();
  await page.getByRole('alert').waitFor();
  const latest=await api.inject({url:'/api/tasks/'+parent.id,headers:{host:'127.0.0.1'}});
  assert.equal(latest.json().result.task.status,'backlog','UI preserves authoritative completion gates');
  await modal.getByRole('button',{name:'Close task details'}).click();
  await page.getByRole('combobox',{name:'Select project'}).click();
  await page.getByRole('option',{name:'Other project',exact:true}).click();
  await page.locator('.board-task').waitFor({state:'detached'});
  await page.getByRole('combobox',{name:'Select project'}).click();
  await page.getByRole('option',{name:'UX regression',exact:true}).click();
  await page.locator('.board-task').filter({hasText:'Parent scope'}).waitFor();
  await page.setViewportSize({width:1440,height:900});
  // The adapter also preserves callbacks and disabled/grouped options in unowned screens.
  await page.evaluate(()=>{
   const label=document.createElement('label');label.textContent='Fixture choice';
   const select=document.createElement('select');select.id='fixture-select';
   select.innerHTML='<option value="">Choose</option><optgroup label="Fruit"><option value="apple">Apple</option><option value="bad" disabled>Apricot</option><option value="banana">Banana</option></optgroup>';
   select.addEventListener('change',()=>select.dataset.changed=select.value);
   label.append(select);document.body.append(label);
  });
  const choice=page.getByRole('combobox',{name:'Fixture choice',exact:true});
  await choice.focus();await choice.press('Alt+ArrowDown');
  assert.equal(await page.getByRole('listbox',{name:'Fixture choice',exact:true}).isVisible(),true);
  await choice.press('Home');await choice.press('ArrowDown');await choice.press('ArrowDown');await choice.press('Enter');
  assert.equal(await page.locator('#fixture-select').getAttribute('data-changed'),'banana','Arrow skips disabled option and callback runs');
  await choice.press('Space');await choice.press('a');await choice.press('Enter');
  assert.equal(await page.locator('#fixture-select').inputValue(),'apple');
  await choice.click();await choice.press('Escape');assert.equal(await choice.getAttribute('aria-expanded'),'false');
  assert.equal(await choice.evaluate(el=>el===document.activeElement),true);
  await page.evaluate(()=>document.getElementById('fixture-select')!.closest('label')!.remove());
  await page.locator('.board-task').filter({hasText:'Parent scope'}).click();
  const lane=modal.getByRole('combobox',{name:'Change task lane'});
  await lane.focus();await lane.press('Shift+Tab');
  assert.equal(await page.locator(':focus').getAttribute('id'),'inspector-panel-0','Portal trigger stays in modal focus trap');
  await lane.click();await lane.press('Escape');assert.equal(await modal.isVisible(),true,'Escape closes select before modal');
  await lane.click();await page.getByRole('option',{name:'To-do',exact:true}).click();
  await modal.locator('.task-inspector-meta').getByText('To-do',{exact:true}).waitFor();
  await modal.getByRole('tab',{name:'Work',exact:true}).click();
  await modal.getByText('Alternatives & decision',{exact:false}).click();
  const size=modal.getByRole('combobox',{name:'Delivery size',exact:true});
  await size.click();await page.getByRole('option',{name:'small',exact:true}).click();
  await modal.getByRole('button',{name:'Save size',exact:true}).click();
  await modal.getByRole('button',{name:'Close task details'}).click();
  await page.getByRole('button',{name:/Skill Engine/}).first().click();
  const filter=page.getByRole('combobox',{name:'Skill status filter'});
  await filter.click();await page.getByRole('option',{name:'Disabled',exact:true}).click();
  assert.equal(await filter.textContent(),'Disabled');
  await page.getByRole('button',{name:/Preview & Visual QA/}).first().click();
  await page.getByRole('combobox',{name:'Link preview to task'}).click();
  await page.getByRole('option',{name:second.displayId+': Second task',exact:true}).click();
  await page.getByPlaceholder('New preview name').fill('Themed preview');
  await page.getByRole('button',{name:'New preview',exact:true}).click();
  await page.getByRole('combobox',{name:'Select Preview'}).getByText('Themed preview').waitFor();
  await page.getByRole('combobox',{name:'Device',exact:true}).first().click();
  await page.getByRole('option',{name:'mobile',exact:true}).click();
  assert.equal(await page.getByRole('combobox',{name:'Device',exact:true}).first().textContent(),'mobile');
  assert.deepEqual(errors,[]);
 }finally{await browser.close();await api.close();fs.rmSync(root,{recursive:true,force:true});}
});
